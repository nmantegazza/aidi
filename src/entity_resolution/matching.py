class VectorizedRelativeNumeric(BaseCompareFeature):
    """Vectorized relative numeric comparator for scale-dependent values.

    Computes:
        sim(x1, x2) = max(0.0, 1.0 - |x1 - x2| / (max(|x1|, |x2|) + eps))
    Special cases:
        - x1 == 0 and x2 == 0 -> 1.0
        - One is 0 and the other non-zero -> 0.0
        - Preserves NaNs.
    """

    def __init__(
        self,
        labels_left: str | list[str] | int,
        labels_right: str | list[str] | int,
        args: tuple = (),
        kwargs: dict | None = None,
        label: str | list[str] | int | None = None,
        eps: float = 1e-9,
    ) -> None:
        """Initialize VectorizedRelativeNumeric comparator.

        Args:
            labels_left: Column label(s) for the left DataFrame.
            labels_right: Column label(s) for the right DataFrame.
            args: Positional arguments for similarity computation.
            kwargs: Keyword arguments for similarity computation.
            label: Identifying label for the returned feature column.
            eps: Epsilon denominator floor to prevent division by zero.
        """
        if kwargs is None:
            kwargs = {}
        super().__init__(
            labels_left,
            labels_right,
            args=args,
            kwargs=kwargs,
            label=label,
        )
        self.eps = eps

    def _compute_vectorized(self, s1: pd.Series, s2: pd.Series) -> pd.Series:
        """Computes relative numeric similarity between series.

        Args:
            s1: Left numeric values.
            s2: Right numeric values.

        Returns:
            pd.Series containing float relative similarity scores in [0.0, 1.0].
        """
        mask_nan = s1.isna() | s2.isna()
        v1 = s1.to_numpy(dtype=float)
        v2 = s2.to_numpy(dtype=float)

        diff = np.abs(v1 - v2)
        max_val = np.maximum(np.abs(v1), np.abs(v2))

        both_zero = (v1 == 0.0) & (v2 == 0.0)
        one_zero = ((v1 == 0.0) & (v2 != 0.0)) | ((v1 != 0.0) & (v2 == 0.0))

        with np.errstate(divide="ignore", invalid="ignore"):
            ratio = diff / (max_val + self.eps)
            sim = np.maximum(0.0, 1.0 - ratio)

        sim[both_zero] = 1.0
        sim[one_zero] = 0.0
        sim[mask_nan.to_numpy()] = np.nan

        return pd.Series(sim, index=s1.index)


def parse_numeric_series(series: pd.Series) -> pd.Series:
    """Robustly parses scalar numeric values from dirty string series.

    Handles currency symbols, thousands separators, European decimal commas,
    and trailing unit labels (e.g. '117 minutes', '$1,299.99', '12,50 €').
    """
    if pd.api.types.is_numeric_dtype(series):
        return pd.to_numeric(series, errors="coerce")

    def clean_val(val):
        if pd.isna(val):
            return np.nan
        if isinstance(val, (int, float)):
            return float(val)
        s = str(val).strip()
        if s.lower() in {
            "nan",
            "none",
            "null",
            "",
            "n/a",
            "free",
            "album only",
            "tbd",
            "unknown",
        }:
            return np.nan
        # Strip currency symbols and surrounding whitespace
        s = re.sub(r"[$€£¥]", "", s).strip()
        # Handle thousands separators vs European decimal commas
        if re.search(r"\d+,\d{3}", s):
            s = s.replace(",", "")
        elif re.search(r"\d+,\d{1,2}$", s):
            s = s.replace(",", ".")
        # Extract continuous numeric token (supports optional negative sign and decimals)
        match = re.search(r"[-+]?\d+(?:\.\d+)?", s)
        if match:
            try:
                return float(match.group(0))
            except ValueError:
                return np.nan
        return np.nan

    return series.apply(clean_val)


def extract_features_and_score(
    candidate_pairs: pd.MultiIndex,
    df_a: pd.DataFrame,
    df_b: pd.DataFrame,
    matching_columns: dict[str, ColumnMatchConfig],
) -> pd.DataFrame:
    """
    Computes pairwise feature similarities for candidate pairs using weighted average.
    
    Args:
        candidate_pairs: MultiIndex generated by the blocking phase.
        df_a: Standardized DataFrame for source A.
        df_b: Standardized DataFrame for source B.
        matching_columns: A mapping of column names to their ColumnMatchConfig (algorithm + weight).
                       
    Returns:
        DataFrame with feature scores and weighted aggregate score.
    """
    if candidate_pairs.empty:
        col_names = list(matching_columns.keys()) + ["aggregate_score"]
        return pd.DataFrame(index=candidate_pairs, columns=col_names)

    valid_cols = [c for c in matching_columns if c in df_a.columns and c in df_b.columns]
    if not valid_cols:
        shared = sorted(set(df_a.columns) & set(df_b.columns))
        raise ValueError(
            f"None of the configured matching columns {list(matching_columns.keys())} "
            f"exist in both input tables. Available shared columns: {shared}"
        )

    compare = recordlinkage.Compare()
    
    # Create copies to avoid mutating original dataframes if type conversion is needed
    df_a_comp = df_a.copy()
    df_b_comp = df_b.copy()

    for col_name, col_config in matching_columns.items():
        algo = col_config.algorithm
        if not algo:
            continue

        if col_name not in df_a.columns or col_name not in df_b.columns:
            continue

        if algo in [
            SimilarityAlgorithm.JAROWINKLER,
            SimilarityAlgorithm.DAMERAU_LEVENSHTEIN,
            SimilarityAlgorithm.COSINE,
        ]:
            # Ensure columns are strings for recordlinkage/rapidfuzz string metrics.
            # Preserves NaNs; converts others (bool, numeric) to string.
            df_a_comp[col_name] = (
                df_a_comp[col_name]
                .astype(str)
                .where(df_a_comp[col_name].notnull(), np.nan)
            )
            df_b_comp[col_name] = (
                df_b_comp[col_name]
                .astype(str)
                .where(df_b_comp[col_name].notnull(), np.nan)
            )

            if algo == SimilarityAlgorithm.COSINE:
                compare.add(VectorizedTFIDF(col_name, col_name, label=col_name))
            else:
                compare.string(
                    col_name,
                    col_name,
                    method=algo.value,
                    label=col_name,
                )
        elif algo == SimilarityAlgorithm.NUMERIC_LINEAR:
            # Parse and sanitize numeric values, stripping units/currency symbols
            df_a_comp[col_name] = parse_numeric_series(df_a_comp[col_name])
            df_b_comp[col_name] = parse_numeric_series(df_b_comp[col_name])
            compare.numeric(
                col_name,
                col_name,
                method="linear",
                offset=0,
                scale=10,
                label=col_name,
            )
        elif algo == SimilarityAlgorithm.NUMERIC_RELATIVE:
            df_a_comp[col_name] = parse_numeric_series(df_a_comp[col_name])
            df_b_comp[col_name] = parse_numeric_series(df_b_comp[col_name])
            compare.add(
                VectorizedRelativeNumeric(col_name, col_name, label=col_name)
            )
        elif algo == SimilarityAlgorithm.DATE:
            # Ensure columns are datetime64[ns] for recordlinkage compatibility (Pandas 2.0+ defaults to [s])
            df_a_comp[col_name] = pd.to_datetime(
                df_a_comp[col_name], errors="coerce"
            ).astype("datetime64[ns]")
            df_b_comp[col_name] = pd.to_datetime(
                df_b_comp[col_name], errors="coerce"
            ).astype("datetime64[ns]")
            compare.date(col_name, col_name, label=col_name)
        elif algo == SimilarityAlgorithm.EXACT:
            compare.exact(col_name, col_name, label=col_name)
        else:
            compare.exact(col_name, col_name, label=col_name)
            
    # Compute the features matrix
    features = compare.compute(candidate_pairs, df_a_comp, df_b_comp)
    
    # Compute an aggregate score using weighted mean: use non-missing features
    # This ensures missing values don't penalize the score.
    mask = pd.DataFrame(index=candidate_pairs, columns=features.columns)
    for col in features.columns:
        # A pair is "missing" for a column if either side has NaN
        val_a = df_a_comp.loc[candidate_pairs.get_level_values(0), col].values
        val_b = df_b_comp.loc[candidate_pairs.get_level_values(1), col].values
        mask[col] = pd.isna(val_a) | pd.isna(val_b)
    
    # Apply mask (NaNs where data was missing)
    features = features.mask(mask.astype(bool))

    # Prepare weights series for the columns present in features
    col_weights = pd.Series(
        {col: matching_columns[col].weight for col in features.columns}
    )

    # Weighted average: sum(score * weight) / sum(weight if score is not NaN)
    # 1. Multiply features by weights (NaNs remain NaNs)
    weighted_scores = features.mul(col_weights, axis=1)

    # 2. Denominator: sum of weights ONLY for non-NaN columns
    # Create a boolean mask of non-NaN values and multiply by weights
    weight_denominator = (
        features.notna().mul(col_weights, axis=1).sum(axis=1)
    )

    # 3. Final aggregate score
    # Use fillna(0) for the numerator sum to handle rows where all features are NaN
    features["aggregate_score"] = (
        weighted_scores.sum(axis=1) / weight_denominator
    ).fillna(0.0)

    return features


def filter_one_to_one_bipartite(
    matched_pairs: pd.MultiIndex,
    scores: pd.Series,
) -> pd.MultiIndex:
    """Filters candidate match pairs to enforce 1-to-1 mutual exclusivity.

    Assigns candidate pairs greedily by descending confidence or aggregate
    score such that each entity in Source A (level 0) and Source B (level 1)
    is matched at most once.

    Args:
        matched_pairs: Positive match pairs MultiIndex.
        scores: Ranking scores Series indexed by candidate pairs.

    Returns:
        Filtered MultiIndex containing only 1-to-1 mutually exclusive matches.
    """
    if matched_pairs.empty:
        return matched_pairs

    pair_scores = scores.reindex(matched_pairs).fillna(-np.inf)
    sorted_pairs = pair_scores.sort_values(ascending=False).index

    seen_a: set[Any] = set()
    seen_b: set[Any] = set()
    selected: list[tuple[Any, Any]] = []

    for a, b in sorted_pairs:
        if a not in seen_a and b not in seen_b:
            seen_a.add(a)
            seen_b.add(b)
            selected.append((a, b))

    if not selected:
        return pd.MultiIndex.from_tuples([], names=matched_pairs.names)

    return pd.MultiIndex.from_tuples(selected, names=matched_pairs.names)


def classify_matches(
    features_df: pd.DataFrame,
    lower_threshold: float = UNCERTAIN_THRESHOLD,
    upper_threshold: float = MATCH_THRESHOLD,
    matching_columns: dict[str, ColumnMatchConfig] | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Classifies scored feature pairs into matches, non-matches, and uncertain.

    Optionally verifies that at least one top-weighted core discriminator column
    was actually compared (non-null in both records), downgrading pairs lacking
    core attribute evidence from matches to uncertain.

    Args:
        features_df: DataFrame returned by `extract_features_and_score` with an
            'aggregate_score' column.
        lower_threshold: Score below which pairs are non-matches.
        upper_threshold: Score above which pairs are definite matches.
        matching_columns: Optional mapping of column names to ColumnMatchConfig
            used to dynamically identify core discriminators.

    Returns:
        Tuple of (matches, non_matches, uncertain) DataFrames.

    Raises:
        ValueError: If 'aggregate_score' is not in features_df.columns.
    """
    if "aggregate_score" not in features_df.columns:
        raise ValueError("features_df must contain 'aggregate_score'")

    scores = features_df["aggregate_score"]

    matches_mask = scores >= upper_threshold
    non_matches_mask = scores < lower_threshold
    uncertain_mask = (scores >= lower_threshold) & (scores < upper_threshold)

    if matching_columns and not features_df.empty:
        weights = [
            c.weight for c in matching_columns.values() if c.weight is not None
        ]
        if weights:
            max_w = max(weights)
            if max_w > 0:
                core_cols = [
                    col
                    for col, c in matching_columns.items()
                    if c.weight is not None
                    and c.weight >= max_w * 0.85
                    and col in features_df.columns
                ]
                if core_cols:
                    core_was_compared = (
                        features_df[core_cols].notna().any(axis=1)
                    )
                    downgrade_mask = matches_mask & (~core_was_compared)
                    matches_mask = matches_mask & core_was_compared
                    uncertain_mask = uncertain_mask | downgrade_mask

    return (
        features_df[matches_mask],
        features_df[non_matches_mask],
        features_df[uncertain_mask],
    )


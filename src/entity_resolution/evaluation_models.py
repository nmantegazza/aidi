"""
Pydantic models for structured evaluation results of the ER pipeline.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field, computed_field

from shared.agents import ExecutionMetadata

from .models import CleaningReport, ERPipelineConfiguration


class EvaluationMetrics(BaseModel):
    """Standard binary classification metrics for a set of match predictions."""
    precision: float = Field(description="TP / (TP + FP). Fraction of predicted matches that are correct.")
    recall: float = Field(description="TP / (TP + FN). Fraction of true matches that were found.")
    f1: float = Field(description="Harmonic mean of precision and recall.")
    tp: int = Field(description="True Positives: predicted matches that are in the ground truth.")
    fp: int = Field(description="False Positives: predicted matches that are NOT in the ground truth.")
    fn: int = Field(description="False Negatives: true matches that were NOT predicted.")
    tn: int | None = Field(default=None, description="True Negatives: non-matches correctly classified as non-matches.")
    support: int = Field(description="Total number of true matches (ground truth size).")
    confusion_matrix: list[list[int]] | None = Field(
        default=None,
        description="2x2 confusion matrix [[TP, FN], [FP, TN]]."
    )


class IndexingEvaluation(BaseModel):
    """Evaluation of the candidate-pair generation (blocking/indexing) stage."""
    num_candidates: int = Field(description="Number of candidate pairs generated by the indexer.")
    max_possible_pairs: int = Field(description="Total possible pairs (|A| * |B|) without blocking.")
    reduction_ratio: float = Field(
        description=(
            "1 - (candidates / max_possible). Proportion of pairs eliminated by indexing. "
            "Higher is better for efficiency."
        )
    )
    pairs_recall: float = Field(
        description=(
            "Fraction of ground-truth matches present in the candidate set. "
            "Should be as close to 1.0 as possible — missed candidates cannot be recovered."
        )
    )
    missed_true_matches: int = Field(
        description="Number of ground-truth matches NOT included in the candidate set."
    )
    num_true_matches: int = Field(description="Total number of ground-truth matches (support).")
    sorting_keys: list[str] | None = Field(default=None, description="The sorting key(s) used for Sorted Neighborhood indexing.")
    window_size: int | None = Field(default=None, description="The window size used for Sorted Neighborhood indexing.")
    indexing_keys: list[str] | None = Field(default=None, description="The key(s) used for candidate indexing.")
    indexing_threshold: float | None = Field(default=None, description="Threshold used for candidate indexing.")


class IndexingBenchmarkReport(BaseModel):
    """Standalone benchmark report for evaluating an indexing strategy."""
    dataset_name: str = Field(description="Name of the dataset evaluated.")
    strategy_name: str = Field(description="Name of the indexing strategy.")
    recall: float = Field(description="Pairs Completeness (Recall).")
    precision: float = Field(description="Pairs Quality (Precision).")
    reduction_ratio: float = Field(description="Search space reduction ratio.")
    indexing_time_sec: float = Field(description="Execution time for indexing in seconds.")
    peak_memory_mb: float = Field(description="Peak memory usage in MB during indexing.")
    peak_cpu_percent: float | None = Field(default=None, description="Peak CPU utilization percentage during indexing.")
    llm_metrics: ExecutionMetadata | None = Field(
        default=None,
        description="LLM execution metadata (time, tokens) if applicable."
    )


class MatchingEvaluation(BaseModel):
    """Evaluation of the deterministic matching (scoring + threshold classification) stage."""
    metrics: EvaluationMetrics
    match_threshold: float = Field(description="The upper threshold used to classify pairs as matches.")
    uncertain_threshold: float = Field(description="The lower threshold; pairs above this are 'uncertain'.")
    num_predicted_matches: int = Field(description="Pairs classified as definite matches by the pipeline.")
    num_uncertain: int = Field(description="Pairs classified as uncertain (between thresholds).")
    num_non_matches: int = Field(description="Pairs classified as non-matches.")


class ColumnValueComparison(BaseModel):
    """Detailed side-by-side comparison for a single column."""
    column_name: str
    val_a: str | None = None
    val_b: str | None = None
    similarity_score: float | None = None


class SamplePair(BaseModel):
    """A sampled pair with comparative column values and similarity score."""
    id_a: str
    id_b: str
    aggregate_score: float
    is_true_match: bool | None = None
    column_comparisons: list[ColumnValueComparison]


class BoundarySamples(BaseModel):
    """Grouped collections of boundary pairs for matches, uncertain, and non-matches."""
    matches_highest: list[SamplePair] = Field(default_factory=list)
    matches_lowest: list[SamplePair] = Field(default_factory=list)
    uncertain_highest: list[SamplePair] = Field(default_factory=list)
    uncertain_lowest: list[SamplePair] = Field(default_factory=list)
    non_matches_highest: list[SamplePair] = Field(default_factory=list)
    non_matches_lowest: list[SamplePair] = Field(default_factory=list)


class EntityResEvalReport(BaseModel):
    """
    Full evaluation report for a single run of the deterministic ER pipeline.
    Aggregates indexing + matching evaluations with run metadata.
    """
    table_name: str = Field(description="Name of the table/dataset being evaluated.")
    timestamp: datetime = Field(default_factory=datetime.now)

    # Dataset metadata
    num_rows_a: int
    num_rows_b: int
    num_ground_truth_matches: int

    # Pipeline Metadata
    er_config: ERPipelineConfiguration | None = Field(
        default=None,
        description="The LLM-generated or override configuration used for this run."
    )
    meta_a: dict[str, Any] | None = Field(default=None, description="Profiling metadata for Source A.")
    meta_b: dict[str, Any] | None = Field(default=None, description="Profiling metadata for Source B.")

    # Cleaning reports
    cleaning_a: CleaningReport | None = Field(default=None)
    cleaning_b: CleaningReport | None = Field(default=None)

    # Execution metadata (model_name, provider, token usage, etc.)
    er_config_metadata: ExecutionMetadata | None = Field(
        default=None,
        description="The execution metadata for the LLM config generation step."
    )

    # Stage evaluations
    indexing: IndexingEvaluation
    matching: MatchingEvaluation

    @computed_field
    @property
    def summary_line(self) -> str:
        """One-line summary for quick display."""
        return (
            f"{self.table_name} | "
            f"Indexing recall={self.indexing.pairs_recall:.2%} RR={self.indexing.reduction_ratio:.2%} | "
            f"Matching P={self.matching.metrics.precision:.2%} "
            f"R={self.matching.metrics.recall:.2%} "
            f"F1={self.matching.metrics.f1:.2%}"
        )


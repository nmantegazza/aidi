"""
Indexing metrics evaluator for assessing candidate pair generation performance.
"""

from __future__ import annotations

from typing import Any

import pandas as pd

from entity_resolution.metrics import (
    compute_precision_recall_f1,
    compute_reduction_ratio,
)


class IndexingMetricsEvaluator:
    """Evaluates candidate-pair generation performance against ground truth."""

    def evaluate(
        self,
        candidate_pairs: pd.MultiIndex,
        ground_truth: pd.MultiIndex,
        df_a: pd.DataFrame,
        df_b: pd.DataFrame,
    ) -> dict[str, Any]:
        """Calculates indexing metrics including recall, precision, and reduction ratio.

        Args:
            candidate_pairs: Candidate record pairs generated by the indexing strategy.
            ground_truth: True matching pairs.
            df_a: Left input DataFrame.
            df_b: Right input DataFrame.

        Returns:
            A dictionary with 'recall', 'precision', and 'reduction_ratio'.
        """
        max_possible_pairs = len(df_a) * len(df_b)
        rr = compute_reduction_ratio(candidate_pairs, max_possible_pairs)
        eval_metrics = compute_precision_recall_f1(
            candidate_pairs, ground_truth, total=max_possible_pairs
        )

        return {
            "recall": eval_metrics.recall,
            "precision": eval_metrics.precision,
            "reduction_ratio": rr,
        }
